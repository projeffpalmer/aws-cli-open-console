def _live_paths():
    from awscli.clidriver import create_clidriver

    paths = {'aws'}

    def visit(prefix, table):
        for name, command in table.items():
            if name == 'help':
                continue
            path = f'{prefix}.{name}'
            paths.add(path)
            visit(path, command.subcommand_table)

    visit('aws', create_clidriver().subcommand_table)
    return paths


