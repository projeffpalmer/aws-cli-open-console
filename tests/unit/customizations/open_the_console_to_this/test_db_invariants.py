def test_placeholders_are_allowed(nodes):
    def check(node, parent, key):
        intent = node.get('intent') or {}
        allowed = BUILTIN_PLACEHOLDERS | set(intent.get('params') or {})
        for template in _templates(node):
            stripped = PLACEHOLDER.sub('', template)
            if '{' in stripped or '}' in stripped:
                return f'unbalanced brace in {template!r}'
            for body in PLACEHOLDER.findall(template):
                if not PLACEHOLDER_SYNTAX.match(body):
                    return f'bad placeholder {{{body}}} in {template!r}'
                if body.split(':')[0] not in allowed:
                    return f'unknown placeholder {{{body}}} in {template!r}'
        return None

    assert _failures(nodes, check) == []


def _host_form_problem(node, parent=None, key=None):
    params = set((node.get('intent') or {}).get('params') or {})
    for template in _templates(node):
        if not template.startswith('https://'):
            return f'not https: {template!r}'
        if template.startswith(REGIONAL_PREFIX):
            continue
        subdomain = SUBDOMAIN_PREFIX.match(template)
        if subdomain and subdomain.group(1).split(':')[0] in params:
            # A curated param as the region subdomain (a region taken
            # from an ARN, aws.kms.schedule-key-deletion).
            continue
        if template.startswith(GLOBAL_PREFIX):
            # Global host: no region subdomain.
            continue
        if '{host}' in template:
            return f'{{host}} in an unexpected host form: {template!r}'
        # Otherwise a special host, kept literal.
    return None


