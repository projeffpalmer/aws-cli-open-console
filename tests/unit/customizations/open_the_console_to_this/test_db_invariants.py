def test_flags_and_scalars_only_with_positionals(nodes):
    def check(node, parent, key):
        has = [k for k in ('flags', 'scalars') if k in node]
        if not node.get('positional'):
            return f'{has} without positional args' if has else None
        if len(has) != 2:
            return 'positional args without both flags and scalars'
        flags, scalars = node['flags'], node['scalars']
        for name in flags + scalars:
            if not isinstance(name, str) or not name or name[0] == '-':
                return f'bad option name {name!r}'
        if flags != sorted(set(flags)) or scalars != sorted(set(scalars)):
            return 'flags/scalars not sorted and unique'
        overlap = set(flags) & set(scalars)
        overlap |= (set(flags) | set(scalars)) & set(node['positional'])
        if overlap:
            return f'option listed twice or as positional: {sorted(overlap)}'
        return None

    assert _failures(nodes, check) == []


