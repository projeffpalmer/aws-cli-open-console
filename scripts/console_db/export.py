"""Write the database (JSON) and its review copies (CSV, STATS.md).

``prepare`` is the single place that turns the pipeline's working tree into
the exported shape: private keys (``_args``, ``_meta``, any ``_x``) are
removed, keys whose value is ``None`` are dropped (absent means null), empty
``children`` are dropped, and ``url.needs_account`` is recomputed from the
templates.  All writers are deterministic: sorted keys, children in name
order, ``\\n`` line endings, no timestamps.
"""

import collections
import csv
import io
import json
import os

from console_db.walk import iter_nodes

SCHEMA_VERSION = 1
CSV_COLUMNS = (
    'path',
    'tier',
    'kind',
    'verb',
    'resource_type',
    'id_args',
    'url_best',
    'url_with_id',
    'url_source',
    'url_verified',
    'docs_best',
    'docs_source',
    'intent_quality',
)
_URL_TEMPLATE_KEYS = ('best', 'with_id', 'with_ids')


def prepare(node):
    """Return an export-ready deep copy of ``node`` and its descendants."""
    out = {}
    for key, value in node.items():
        if key.startswith('_') or value is None:
            continue
        if key == 'children':
            if value:
                out[key] = {name: prepare(value[name]) for name in value}
            continue
        if isinstance(value, dict):
            value = _drop_none(value)
        out[key] = value
    if isinstance(out.get('url'), dict):
        out['url']['needs_account'] = _needs_account(out['url'])
    return out


def write_json(root, meta, path):
    data = {'schema': SCHEMA_VERSION, 'generated': meta, 'root': prepare(root)}
    text = json.dumps(
        data, sort_keys=True, separators=(',', ':'), ensure_ascii=False
    )
    _write_text(path, text + '\n')


def write_csv(root, path):
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator='\n')
    writer.writerow(CSV_COLUMNS)
    for node in iter_nodes(root):
        intent = node.get('intent') or {}
        url = node.get('url') or {}
        docs = node.get('docs') or {}
        writer.writerow(
            [
                node['path'],
                node['tier'],
                node['kind'],
                intent.get('verb') or '',
                intent.get('resource_type') or '',
                ' '.join(intent.get('id_args') or []),
                url.get('best') or '',
                url.get('with_id') or '',
                url.get('source') or '',
                url.get('verified') or '',
                docs.get('best') or '',
                docs.get('source') or '',
                node.get('_intent_quality') or '',
            ]
        )
    _write_text(path, buf.getvalue())


def write_stats(root, path, meta=None):
    nodes = list(iter_nodes(root))
    lines = ['# Console database stats', '']
    lines.append('Generated by `scripts/gen-console-db`; do not edit by hand.')
    if meta:
        lines.append('')
        for key in sorted(meta):
            lines.append(f'- {key}: {meta[key]}')
    lines += ['', f'Nodes: {len(nodes)}', '']
    lines += _table(
        'Nodes per tier and kind',
        ('tier', 'kind'),
        collections.Counter((n['tier'], n['kind']) for n in nodes),
    )
    lines += _table(
        '`url.source` by tier',
        ('tier', 'url.source'),
        collections.Counter(
            (n['tier'], (n.get('url') or {}).get('source')) for n in nodes
        ),
    )
    lines += _table(
        '`url.verified`',
        ('url.verified',),
        collections.Counter(
            ((n.get('url') or {}).get('verified'),) for n in nodes
        ),
    )
    lines += _table(
        '`docs.source` by tier',
        ('tier', 'docs.source'),
        collections.Counter(
            (n['tier'], (n.get('docs') or {}).get('source')) for n in nodes
        ),
    )
    lines += _table(
        '`intent.verb` (tier 2 and 3)',
        ('verb',),
        collections.Counter(
            ((n.get('intent') or {}).get('verb'),)
            for n in nodes
            if n['tier'] >= 2
        ),
    )
    lines += _intent_coverage(nodes)
    lines += _table(
        'Intent match quality (operations and waiters)',
        ('tier', 'kind', 'quality'),
        collections.Counter(
            (n['tier'], n['kind'], n.get('_intent_quality'))
            for n in nodes
            if n['kind'] in ('operation', 'waiter')
        ),
    )
    lines += _table(
        '`url.with_id` present (tier 2 and 3)',
        ('with_id',),
        collections.Counter(
            (bool((n.get('url') or {}).get('with_id')),)
            for n in nodes
            if n['tier'] >= 2
        ),
    )
    _write_text(path, '\n'.join(lines).rstrip('\n') + '\n')


def _intent_coverage(nodes):
    ops = [n for n in nodes if n['tier'] == 2 and n['kind'] == 'operation']
    typed = [n for n in ops if (n.get('intent') or {}).get('resource_type')]
    lines = ['## Intent coverage', '']
    lines.append(
        f'Tier-2 operations with a resource type: {len(typed)} of '
        f'{len(ops)} ({_percent(len(typed), len(ops))})'
    )
    with_ns = {
        n['path']
        for n in nodes
        if n['tier'] == 1 and (n.get('console') or {}).get('namespaces')
    }
    in_ns = [n for n in ops if n['path'].rsplit('.', 1)[0] in with_ns]
    typed_in_ns = [n for n in typed if n['path'].rsplit('.', 1)[0] in with_ns]
    lines.append('')
    lines.append(
        'Tier-2 operations of services with CloudFormation namespaces: '
        f'{len(typed_in_ns)} of {len(in_ns)} '
        f'({_percent(len(typed_in_ns), len(in_ns))})'
    )
    lines.append('')
    return lines


def _percent(part, whole):
    return f'{100.0 * part / whole:.1f} %' if whole else 'n/a'


def _table(title, headers, counter):
    lines = [f'## {title}', '']
    lines.append('| ' + ' | '.join(headers + ('nodes',)) + ' |')
    lines.append('|' + '---|' * (len(headers) + 1))
    for key in sorted(counter, key=_sort_key):
        cells = ['(none)' if part is None else str(part) for part in key]
        lines.append('| ' + ' | '.join(cells + [str(counter[key])]) + ' |')
    lines.append('')
    return lines


def _sort_key(key):
    return tuple((part is None, str(part)) for part in key)


def _drop_none(value):
    if isinstance(value, dict):
        return {k: _drop_none(v) for k, v in value.items() if v is not None}
    if isinstance(value, list):
        return [_drop_none(v) for v in value]
    return value


def _needs_account(url):
    templates = [url.get(key) or '' for key in _URL_TEMPLATE_KEYS]
    templates += [v.get('template') or '' for v in url.get('variants') or []]
    return any('{account' in t for t in templates)


def _write_text(path, text):
    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
